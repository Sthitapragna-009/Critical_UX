// Builds the files Figma loads.
//   node figma-plugin/build.js                      -> code.js + ui.html (this folder, for the manifest import)
//   node figma-plugin/build.js --generative <dir>   -> <dir>/code.ts + <dir>/ui.html for a Figma-hosted plugin,
//                                                      without deep review (no authenticated network calls there)
const fs = require("fs");
const path = require("path");
const dir = __dirname;
const read = (f) => fs.readFileSync(path.join(dir, f), "utf8");
const rules = read("src/rules.js");
const code = [rules, read("src/engine.js"), read("src/figma-main.js")].join("\n\n");
const ui = read("src/ui.html").replace("/*__RULES__*/", rules);

const gi = process.argv.indexOf("--generative");
if (gi > -1) {
  const out = path.resolve(process.argv[gi + 1] || "generative");
  fs.mkdirSync(out, { recursive: true });
  const start = ui.indexOf("// ---------------- deep review");
  const end = ui.indexOf("// ---------------- patterns");
  if (start < 0 || end < 0) throw new Error("deep review markers missing in src/ui.html");
  const genUi = (ui.slice(0, start) + "// deep review is not available in the Figma-hosted version\nfunction deepReview() { return Promise.reject(new Error(\"Not available\")); }\n\n" + ui.slice(end))
    .replace("/*__DEEP__*/true", "false");
  if (/api\.anthropic\.com|x-api-key/.test(genUi)) throw new Error("network code left in generative UI");
  fs.writeFileSync(path.join(out, "code.ts"), "/* eslint-disable */\n// @ts-nocheck\n// criticalUX, generated from figma-plugin/src by build.js --generative\n" + code);
  fs.writeFileSync(path.join(out, "ui.html"), genUi);
  console.log("Built generative plugin in " + out);
} else {
  const banner = "// Generated by build.js from src/. Edit the files in src/, then run: node figma-plugin/build.js\n";
  fs.writeFileSync(path.join(dir, "code.js"), banner + code);
  fs.writeFileSync(path.join(dir, "ui.html"), ui.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build.js from src/ui.html -->"));
  console.log("Built code.js and ui.html");
}
